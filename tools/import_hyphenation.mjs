#!/usr/bin/env node
/* Convert TeX hyphenation patterns (hyph-utf8, e.g. hyph-de-1996.tex) into an engine module.
 *
 * Usage:
 *   curl -LO https://raw.githubusercontent.com/hyphenation/tex-hyphen/master/hyph-utf8/tex/generic/hyph-utf8/patterns/tex/hyph-de-1996.tex
 *   node tools/import_hyphenation.mjs hyph-de-1996.tex de-1996 > engine/hyph/de-1996.js
 *
 * The module keeps the licence header of the source file and the patterns as one space-separated string. */
import { readFileSync } from 'node:fs';

const [file, tag] = process.argv.slice(2);
if (!file || !tag) {
  console.error('usage: import_hyphenation.mjs FILE.tex TAG > engine/hyph/TAG.js');
  process.exit(2);
}
const src = readFileSync(file, 'utf8');
const header = src.slice(0, src.indexOf('% ====')).split('\n').filter((l) => l.startsWith('%')).map((l) => l.slice(1));
const body = (re) => {
  const m = src.match(re);
  if (!m) return [];
  return m[1].split('\n').map((l) => l.replace(/%.*/, '').trim()).join(' ').split(/\s+/).filter(Boolean);
};
const patterns = body(/\\patterns\{([\s\S]*?)\n\}/);
const exceptions = body(/\\hyphenation\{([\s\S]*?)\n\}/);
const num = (key) => {
  const m = src.match(new RegExp(`typesetting:[\\s\\S]*?${key}:\\s*(\\d+)`));
  return m ? Number(m[1]) : 2;
};
if (!patterns.length) throw new Error('no \\patterns found');
const out = [
  '// Generated by tools/import_hyphenation.mjs - do not edit.',
  `// Source: ${file.split('/').pop()} (hyph-utf8, https://github.com/hyphenation/tex-hyphen)`,
  '//',
  ...header.map((l) => '//' + l),
  '',
  'export default {',
  `  tag: ${JSON.stringify(tag)},`,
  `  leftmin: ${num('left')},`,
  `  rightmin: ${num('right')},`,
  `  exceptions: ${JSON.stringify(exceptions.join(' '))},`,
  `  patterns: ${JSON.stringify(patterns.join(' '))},`,
  '};',
  '',
];
process.stdout.write(out.join('\n'));
console.error(`${patterns.length} patterns, ${exceptions.length} exceptions`);
